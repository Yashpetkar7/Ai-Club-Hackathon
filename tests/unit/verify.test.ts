const verdictOf = async (line: string): Promise<{ verdict: Verdict; reasons: string[] }> => {
  const { references } = extractReferences(line);
  expect(references.length, `should find one reference in: ${line.slice(0, 80)}`).toBe(1);
  const c = await checkReference(references[0]!, registries);
  return { verdict: c.verdict, reasons: c.reasons };
};

