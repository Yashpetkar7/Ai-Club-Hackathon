describe('names from every language are compared fairly', () => {
  const base = { registry: 'crossref' as const, id: 'x', title: 'A study of reading habits in four cities', year: 2022, retracted: false };
  it.each([
    ['Elamın', 'Elamin'],
    ['Günsaldı', 'Gunsaldi'],
    ['Batı', 'Bati'],
    ['Łukasiewicz', 'Lukasiewicz'],
    ['Sørensen', 'Sorensen'],
    ['Weiß', 'Weiss'],
    ['Đorđević', 'Dordevic'],
    ['van der Aalst', 'Aalst'],
    ['García-Márquez', 'Garcia Marquez'],
    ["O'Connor", 'O’Connor'],
  ])('%s and %s are the same person', (a, b) => {
    for (const [x, y] of [[a, b], [b, a]] as const) {
      const c = compare({ raw: '', title: base.title, authors: [x], year: 2022 }, { ...base, authors: [{ family: y }] });
      expect(c.authors, `${x} / ${y}`).toBe(1);
      expect(c.firstAuthor).toBe(true);
    }
  });
  it('different people stay different', () => {
    const c = compare({ raw: '', title: base.title, authors: ['Lee'], year: 2022 }, { ...base, authors: [{ family: 'Li' }] });
    expect(c.authors).toBe(0);
  });
  it('a registry with no authors says so instead of blaming the student', () => {
    const c = compare({ raw: '', title: base.title, authors: ['Kumar'], year: 2022 }, { ...base, authors: [] });
    expect(c.authorsUnknown).toBe(true);
  });
});

describe('a registry that does not answer is never a pass and never a "not found"', () => {
  const down = async (): Promise<never> => {
    throw new Error('network error');
  };
  const dead: Registries = { crossrefByDoi: down, openalexByDoi: down, dataciteByDoi: down, doiExists: down, crossrefSearch: down };
  const refs: RawReference[] = [parseReference('Noy, S., & Zhang, W. (2023). Experimental evidence on the productivity effects of generative artificial intelligence. Science. https://doi.org/10.1126/science.adh2586'), parseReference('Noy, S., & Zhang, W. (2023). Experimental evidence on the productivity effects of generative artificial intelligence. Science.'), { raw: '10.1126/science.adh2586', doi: '10.1126/science.adh2586' }];
  it.each(refs)('could not check: $raw', async (ref) => {
    const c = await checkReference(ref, dead);
    expect(c.verdict).toBe('could-not-check');
    expect(c.reasons).toContain('REGISTRY_UNREACHABLE');
    expect(c.trace.every((t) => t.status === 'error')).toBe(true);
  });
});

describe('one registry is not enough for green', () => {
  const rec = { registry: 'crossref' as const, id: '10.1234/x', doi: '10.1234/x', title: 'A study of reading habits in four cities', authors: [{ family: 'Noy' }], year: 2022, retracted: false };
  const line = 'Noy, S. (2022). A study of reading habits in four cities. Journal of Reading, 1(1). https://doi.org/10.1234/x';
  const none = async () => null;
  const fail = async (): Promise<never> => { throw new Error('network error'); };
  const base: Registries = { crossrefByDoi: async () => rec, openalexByDoi: async () => ({ ...rec, registry: 'openalex' }), dataciteByDoi: none, doiExists: async () => true, crossrefSearch: async () => [rec] };
  it('both answer: confirmed', async () => expect((await checkReference(parseReference(line), base)).verdict).toBe('confirmed'));
  it('the second answers that it has no record: one registry only, and the receipt says so', async () => {
    const c = await checkReference(parseReference(line), { ...base, openalexByDoi: none });
    expect(c.verdict).toBe('one-registry');
    expect(c.reasons).toContain('SECOND_REGISTRY_NO_RECORD');
    expect(c.trace.find((x) => x.registry === 'openalex')?.status).toBe('not-found');
  });
  it.each([['full reference', line], ['bare DOI', '10.1234/x']])('the second is down, %s: one registry only', async (_n, l) => {
    const c = await checkReference(extractReferences(l).references[0]!, { ...base, openalexByDoi: fail });
    expect(c.verdict).toBe('one-registry');
    expect(c.reasons).toEqual(['SECOND_REGISTRY_UNREACHABLE']);
  });
  it('a problem found by one registry stands even when the other is down', async () => {
    expect((await checkReference(parseReference(line.replace('2022', '2012')), { ...base, openalexByDoi: fail })).verdict).toBe('details-differ');
    expect((await checkReference(parseReference(line), { ...base, crossrefByDoi: async () => ({ ...rec, retracted: true }), openalexByDoi: fail })).verdict).toBe('retracted');
  });
  it('DataCite works get a second look too', async () => {
    const dc = { ...base, crossrefByDoi: none, dataciteByDoi: async () => ({ ...rec, registry: 'datacite' as const }) };
    expect((await checkReference(parseReference(line), dc)).verdict).toBe('confirmed');
    expect((await checkReference(parseReference(line), { ...dc, openalexByDoi: async () => ({ ...rec, registry: 'openalex' as const, retracted: true }) })).verdict).toBe('retracted');
    expect((await checkReference(parseReference(line), { ...dc, openalexByDoi: fail })).verdict).toBe('one-registry');
  });
  it('a DOI we could not look up is not excused by a title match with another DOI', async () => {
    const c = await checkReference(parseReference(line.replace('10.1234/x', '10.1234/other')), { ...base, crossrefByDoi: fail, dataciteByDoi: fail });
    expect(c.verdict).toBe('could-not-check');
  });
});

describe('reading pasted text', () => {
  it('splits a wrapped bibliography and flags citations with no entry', () => {
    const text = `Generative AI made writers faster (Noy & Zhang, 2023). Others disagree (Hargrove, 2024).

References

Noy, S., & Zhang, W. (2023). Experimental evidence on the productivity effects of
generative artificial intelligence. Science, 381(6654), 187–192.
https://doi.org/10.1126/science.adh2586
Krugman, P. (1991). Increasing returns and economic geography. Journal of Political
Economy, 99(3), 483–499.`;
    const x = extractReferences(text);
    expect(x.references).toHaveLength(2);
    expect(x.references[0]).toMatchObject({ doi: '10.1126/science.adh2586', year: 2023, authors: ['Noy', 'Zhang'] });
    expect(x.references[1]).toMatchObject({ title: 'Increasing returns and economic geography', authors: ['Krugman'] });
    expect(x.orphanCitations).toEqual(['Hargrove, 2024']);
  });
  it('returns nothing for empty or ordinary prose', () => {
    expect(extractReferences('').references).toHaveLength(0);
    expect(extractReferences('I think remote work is good for people. It saves time and money for most of us every single day, and that matters a lot to families who live far from the city where their office happens to be, as everyone knows.').references).toHaveLength(0);
  });
  it('keeps DOIs that contain brackets', () => {
    expect(extractReferences('10.1016/S0140-6736(97)11096-0').references[0]?.doi).toBe('10.1016/s0140-6736(97)11096-0');
  });
});
