// @vitest-environment node
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { CitationStyle, RegistryRecord, Source } from '@/core/contracts';
import { recordToCsl } from '@/core/cite/csl';
import { formatItems, formatSources, STYLE_FILE, toRuns, type StyleFiles } from '@/core/cite/engine';
import { sentenceCase } from '@/core/cite/sentenceCase';
import { fromCrossref } from '@/core/registries/map';

const store = JSON.parse(readFileSync('tests/unit/fixtures/registry.json', 'utf8'));
const file = (n: string): string => readFileSync(`public/styles/${n}`, 'utf8');
export const styleFiles = (s: CitationStyle): StyleFiles => ({ style: file(`${STYLE_FILE[s]}.csl`), locales: { 'en-US': file('locales-en-US.xml'), 'en-GB': file('locales-en-GB.xml') } });
const real = (doi: string): RegistryRecord => fromCrossref(store[`https://api.crossref.org/works/${doi}`].body.message);
const apa = styleFiles('apa');
const one = (r: RegistryRecord) => {
  const out = formatItems([recordToCsl('a', r, { sentence: true })], 'apa', apa);
  return { text: out.entries[0]!.text, inText: out.inText.get('a')!, italics: out.entries[0]!.runs.filter((x) => x.italic).map((x) => x.text) };
};

// Expected strings worked out by hand from the APA 7 rules before the engine was run. Never paste engine output here.
describe('APA 7 reference list', () => {
  it('two authors, journal with volume, issue and pages', () => {
    const r = one(real('10.1126/science.adh2586'));
    expect(r.text).toBe('Noy, S., & Zhang, W. (2023). Experimental evidence on the productivity effects of generative artificial intelligence. Science, 381(6654), 187–192. https://doi.org/10.1126/science.adh2586');
    expect(r.inText).toBe('(Noy & Zhang, 2023)');
    expect(r.italics.join('')).toContain('Science');
    expect(r.italics.join('')).toContain('381');
    expect(r.italics.join('')).not.toContain('6654');
  });
  it('four authors, question mark in the title, issue year instead of online year', () => {
    const r = one(real('10.1093/qje/qju032'));
    expect(r.text).toBe('Bloom, N., Liang, J., Roberts, J., & Ying, Z. J. (2015). Does working from home work? Evidence from a Chinese experiment. The Quarterly Journal of Economics, 130(1), 165–218. https://doi.org/10.1093/qje/qju032');
    expect(r.inText).toBe('(Bloom et al., 2015)');
  });
  it('title case becomes sentence case, capital after the colon', () => {
    expect(one(real('10.1257/aer.20160696')).text).toBe('Acemoglu, D., & Restrepo, P. (2018). The race between man and machine: Implications of technology for growth, factor shares, and employment. American Economic Review, 108(6), 1488–1542. https://doi.org/10.1257/aer.20160696');
  });
  it('one author', () => {
    const r = one(real('10.1086/261763'));
    expect(r.text).toBe('Krugman, P. (1991). Increasing returns and economic geography. Journal of Political Economy, 99(3), 483–499. https://doi.org/10.1086/261763');
    expect(r.inText).toBe('(Krugman, 1991)');
  });
  it('article number instead of pages, and ChatGPT keeps its capitals', () => {
    expect(one(real('10.1038/s41598-023-41032-5')).text).toBe('Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in the bibliographic citations generated by ChatGPT. Scientific Reports, 13(1), Article 14045. https://doi.org/10.1038/s41598-023-41032-5');
  });
  it('two authors with middle initials, 1995', () => {
    expect(one(real('10.1037/0033-2909.117.3.497')).text).toBe('Baumeister, R. F., & Leary, M. R. (1995). The need to belong: Desire for interpersonal attachments as a fundamental human motivation. Psychological Bulletin, 117(3), 497–529. https://doi.org/10.1037/0033-2909.117.3.497');
  });
  it('twenty-one or more authors: first nineteen, an ellipsis, the last one; no issue number', () => {
    const rec = real('10.1016/j.ijinfomgt.2023.102642');
    expect(rec.authors.length).toBeGreaterThan(21);
    const r = one(rec);
    expect(r.text).toMatch(/^Dwivedi, Y\. K\., Kshetri, N\., Hughes, L\., /);
    expect(r.text).toMatch(/ \. \. \. \p{Lu}[^.]+, \p{Lu}\..* \(2023\)\. /u);
    expect(r.text.split('. . .')[0]!.match(/, \p{Lu}\./gu)!.length).toBe(19);
    expect(r.text).not.toContain('&');
    expect(r.text).toContain('Opinion paper: “So what if ChatGPT wrote it?” Multidisciplinary perspectives on opportunities, challenges and implications of generative conversational AI for research, practice and policy. International Journal of Information Management, 71, Article 102642. https://doi.org/10.1016/j.ijinfomgt.2023.102642');
    expect(r.inText).toBe('(Dwivedi et al., 2023)');
  });
  it('no year is n.d.', () => {
    const { year: _y, printYear: _p, ...rest } = real('10.1086/261763');
    const r = one(rest);
    expect(r.text).toMatch(/^Krugman, P\. \(n\.d\.\)\. /);
    expect(r.inText).toBe('(Krugman, n.d.)');
  });
  it('a registry title with a leading retraction notice is cited by its own title', () => {
    expect(one(real('10.1108/jrit-01-2024-0017')).text).toContain('ChatGPT in the classroom: Navigating the generative AI wave in management education. Journal of Research in Innovative Teaching & Learning');
  });
  it('two works by the same author in the same year get a and b', () => {
    const k = real('10.1086/261763');
    const out = formatItems([recordToCsl('a', k, { sentence: true }), recordToCsl('b', { ...k, title: 'Another paper about trade', id: 'x' }, { sentence: true })], 'apa', apa);
    expect([...out.inText.values()].sort()).toEqual(['(Krugman, 1991a)', '(Krugman, 1991b)']);
  });
  it('a web page by an organisation', () => {
    const s: Source = { id: 'w', projectId: 'p', origin: 'web', raw: { raw: 'x', title: 'Generative AI Guidance for Students', authors: ['Example University'], year: 2025, container: 'Example Site', url: 'https://example.org/ai' }, keys: { found: false, checked: false, approved: true }, keptWithReason: 'official guidance page', tags: [], notes: '', addedAt: '' };
    const out = formatSources([s], 'apa', apa);
    expect(out.entries[0]!.text).toBe('Example University. (2025). Generative AI guidance for students. Example Site. https://example.org/ai');
    expect(out.inText.get('w')).toBe('(Example University, 2025)');
  });
});

describe('the other four styles', () => {
  const recs = ['10.1126/science.adh2586', '10.1086/261763'].map(real);
  it.each(['harvard', 'mla', 'chicago', 'ieee'] as const)('%s lists both works with a DOI', (st) => {
    const out = formatItems(recs.map((r) => recordToCsl(r.id, r, { sentence: st !== 'mla' && st !== 'chicago' })), st, styleFiles(st));
    expect(out.entries).toHaveLength(2);
    for (const e of out.entries) expect(e.text).toMatch(/10\.\d{4}\//);
    expect(out.entries.some((e) => e.runs.some((r) => r.italic))).toBe(true);
  });
  it('IEEE numbers follow the order given', () => {
    const out = formatItems([recs[1]!, recs[0]!].map((r) => recordToCsl(r.id, r, { sentence: true })), 'ieee', styleFiles('ieee'));
    expect(out.inText.get('10.1086/261763')).toBe('[1]');
    expect(out.entries[0]!.label).toBe('[1]');
    expect(out.entries[0]!.text).toContain('P. Krugman');
  });
  it('MLA and Chicago keep title case', () => {
    for (const st of ['mla', 'chicago'] as const) expect(formatItems([recordToCsl('a', recs[0]!, { sentence: false })], st, styleFiles(st)).entries[0]!.text).toContain('Productivity Effects of Generative Artificial Intelligence');
  });
});

describe('sentence case', () => {
  it.each([
    ['The Impact of AI on Higher Education in the UAE', 'The impact of AI on higher education in the UAE'],
    ['COVID-19 and Online Learning: A Meta-Analysis', 'COVID-19 and online learning: A meta-analysis'],
    ['Does GPT-4 Pass the Bar Exam? Evidence From U.S. Law Schools', 'Does GPT-4 pass the bar exam? Evidence from U.S. law schools'],
    ['A Bayesian Model of Chinese Consumers', 'A Bayesian model of Chinese consumers'],
    ['iPhone Use and Sleep', 'iPhone use and sleep'],
    ['MANAGING CHANGE IN SMALL FIRMS', 'Managing change in small firms'],
    ['Already written in sentence case: a study', 'Already written in sentence case: A study'],
  ])('%s', (a, b) => expect(sentenceCase(a).text).toBe(b));
  it('flags words it lowered, so the student can put a name back', () => {
    expect(sentenceCase('Leadership Lessons From Shackleton').check).toContain('Shackleton');
    expect(sentenceCase('Experimental evidence on the productivity effects of generative artificial intelligence').check).toEqual([]);
  });
});

it('markup from a registry can never reach the page', () => {
  const r = { ...real('10.1086/261763'), title: 'A <script>alert(1)</script> title & more' };
  const t = one(r);
  expect(t.text).not.toContain('<script');
  expect(toRuns('a <i>b</i> &amp; c').map((x) => [x.text, !!x.italic])).toEqual([['a ', false], ['b', true], [' & c', false]]);
});
